def _league(t: str) -> Optional[str]:
    """リーグ戦の大会名を「連盟名＋部＋季」にする。連盟名以外の語が残るものは None。"""
    s = re.sub(r'\s+', '', _z2h(t))
    # 試合名などが入っているもの・リーグ名がないものは触らない
    if s.startswith('大学') or (s.endswith('戦') and not s.endswith('リーグ戦')):
        return None
    if re.fullmatch(r'東海地区大学野球(春|秋)季リーグ戦・静岡県リーグ', s):
        return '静岡' + ('秋季' if '秋' in s else '春季')
    name = next((n for pat, n in _LEAGUES if re.search(pat, s)), None)
    if not name:
        return None
    season = '秋季' if '秋' in s else '春季' if '春' in s else ''
    m = re.search(r'([1-4一二])部', s)
    div = ({'一': '1', '二': '2'}.get(m.group(1), m.group(1)) + '部') if m else ''
    kept = re.sub(r'20\d\d年?|\d\d(?=春|秋)', '', s)
    rest = re.sub(r'[（）()・]', '', kept)
    rest = re.sub(_LEAGUE_WORDS, '', rest)
    rest = re.sub(r'大学|野球|連盟|リーグ戦?|春季|秋季|春期|秋期|春|秋|[1-4一二]部|一部リーグ|静岡県', '', rest)
    if rest:
        return None
    return name + div + season


def short_tournament_name(t: Optional[str], type_: Optional[str] = None, year: Optional[int] = None) -> Optional[str]:
    """大会名を短い表記にする（例：第107回全国高等学校野球選手権大会 → 甲子園）。"""
    if not t:
        return t
    s0 = t
    s = _z2h(t).strip()

    def has(p):
        return re.search(p, s)

    # 高校・中学の全国大会
    if has(r'選抜高(校|等学校)野球|^センバツ$'):
        return 'センバツ'
    if has(r'全国中学校軟式野球大会|^中学全国大会\s*[（(]軟式野球[）)]$|^全国大会[（(]中学軟式野球[）)]$'):
        return '全中'
    if has(r'^全国高等学校軟式野球選手権大会$'):
        return '全国高校軟式'
    if has(r'軟式'):
        return s0
    if has(r'^20\d\d年秋季高校野球公式戦$'):
        return '秋季公式戦'
    if has(r'^四国アイランドリーグplus'):
        return re.sub(r'^四国アイランドリーグplus\s*', '四国IL', s)
    if has(r'^新潟県高等学校野球連盟'):
        return re.sub(r'^新潟県高等学校野球連盟\s*', '新潟県高野連 ', s).strip()
    if has(r'全国高(校|等学校)野球選手権'):
        return '甲子園'
    if has(r'^甲子園[（(]?交流試合[）)]?$'):
        return '甲子園交流試合'
    if has(r'明治神宮野球大会'):
        return '神宮大会'
    if has(r'(全日本)?大学野球選手権|^全日本大学選手権$'):
        return '全日本選手権'
    if has(r'^(第\d+回)?都市対抗野球大会$'):
        return '都市対抗'
    if has(r'^(第\d+回)?\s*社会人野球日本選手権大会$'):
        return '日本選手権'
    if has(r'^(国体|国民体育大会|国民スポーツ大会)$'):
        return '国スポ' if (year or 0) >= 2024 else '国体'
    if has(r'^ジャイアンツ(杯|カップ)$'):
        return 'ジャイアンツ杯'
    # 地区大会：「秋季九州地区高校野球大会」→「秋季九州大会」
    m = re.fullmatch(r'(春季|秋季)(.+?)(地区|県|府)?高(校|等学校)野球(公式戦|大会)', s)
    if m:
        return m.group(1) + m.group(2) + '大会'
    # 侍ジャパン・国際大会
    if has(r'U-?18.*(ワールドカップ|W杯)'):
        return 'U-18W杯'
    if has(r'U-?15.*(ワールドカップ|W杯)'):
        return 'U-15W杯'
    if has(r'U-?23\s*(ワールドカップ|W杯)'):
        return 'U-23W杯'
    if has(r'U-?12\s*(ワールドカップ|W杯)'):
        return 'U-12W杯'
    if has(r'BFA\s*U-?18アジア選手権'):
        return 'U-18アジア選手権'
    if has(r'^第\d+回\s*BFA\s*アジア選手権$'):
        return 'アジア選手権'
    m = re.fullmatch(r'U-?(12|15)アジア選手権', s)
    if m:
        return f'U-{m.group(1)}アジア選手権'
    if has(r'ワールド\s*カレッジ\s*ベースボール\s*チャンピオンシップ'):
        return 'WCBC'
    if has(r'ハーレム'):
        return 'ハーレム大会'
    if has(r'プラハ'):
        return 'プラハ大会'
    if has(r'大学.*選考合宿|^代表候補選考合宿$'):
        return '大学代表選考合宿'
    if has(r'大学(日本)?代表候補(強化)?(合宿)?$|^代表候補強化合宿$'):
        return '大学代表候補合宿'
    if has(r'(U-?18|高校)(日本)?代表?(候補)?(強化)?合宿|U18候補合宿'):
        return 'U-18候補合宿'
    if has(r'U-?18壮行試合'):
        return 'U-18壮行試合'
    m = re.fullmatch(r'U-?(15|18)(日本)?代表', s)
    if m:
        return f'U-{m.group(1)}代表'
    if has(r'^大学日本代表$'):
        return '大学代表'
    if has(r'MCYSA全米選手権'):
        return '全米選手権'
    if re.fullmatch(r'U-?15全米選手権', s):
        return 'U-15全米選手権'
    if has(r'^第\d+回世界少年野球大会$'):
        return '世界少年野球大会'
    # JABA など「第N回」だけ外す
    m = re.fullmatch(r'第\d+回\s*(JABA.+)', s)
    if m:
        return m.group(1)
    if type_ == 'title':
        lg = _league(s)
        if lg:
            return lg
    return s0


