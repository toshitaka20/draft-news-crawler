def short_result(r):
    """結果を短い表記にする（例：ベストナイン 外野手 → ベストナイン（外野）、最高殊勲選手賞 → MVP）。"""
    if r is None:
        return r
    s = _z2h(str(r)).strip()
    if s == 'None':
        return s
    m = re.fullmatch(r'(ベストナイン|ベスト9)(賞)?\s*[（(・ ]?\s*([^）)]*?)\s*[）)]?', s)
    if m:
        inner = m.group(3)
        if not inner:
            return 'ベストナイン'
        parts = [_POS.get(p) or {'春': '春', '秋': '秋'}.get(p) for p in re.split(r'[・、]', inner)]
        if all(parts):
            return 'ベストナイン（' + '・'.join(parts) + '）'
        return s
    m = re.fullmatch(r'優秀選手\s*[（(]?\s*(外野手|二塁手|三塁手)\s*[）)]?', s)
    if m:
        return f'優秀選手（{_POS[m.group(1)]}）'
    if s in _RESULT_MAP:
        return _RESULT_MAP[s]
    # 「優勝（決勝で…）」のような説明つきは、説明を外す
    m = re.fullmatch(r'(優勝|準優勝|ベスト\d+|\d回戦)[（(].+[）)]', s)
    if m:
        return m.group(1)
    if re.fullmatch(r'8強[（(].+[）)]', s):
        return 'ベスト8'
    if re.fullmatch(r'4強[（(].+[）)]', s):
        return 'ベスト4'
    m = re.fullmatch(r'(首位打者)(賞)?\s*打率(\.\d+)', s)
    if m:
        return f'首位打者（{m.group(3)}）'
    m = re.fullmatch(r'(打点王|盗塁王)\s*[（(](\d+)(打点|盗塁)[）)]', s)
    if m:
        return f'{m.group(1)}（{m.group(2)}）'
    if re.fullmatch(r'最優秀投手賞\s+(.+)', s):
        return '最優秀投手'
    return r
